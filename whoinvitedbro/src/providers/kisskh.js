import { USER_AGENT, empty, parseJson, isHttp, simplify, languageName } from "../util.js";
import { ENC_DEC, encGet } from "../encdec.js";

const BASE = "https://kisskh.is";

/** The KissKH entry of a title: the only result, else the same title (with "Season N" for later seasons). */
export function pick(results, data) {
    const list = Array.isArray(results) ? results : [];
    if (list.length === 1) return list[0];
    const title = simplify(data.title);
    if (data.type === "movie") return list.find(r => simplify(r.title) === title) || null;
    const season = data.season || 1;
    return list.find(r => simplify(r.title) === title + "season" + season)
        || (season === 1 ? list.find(r => simplify(r.title) === title) : null)
        || null;
}

export default {
    id: "kisskh",
    name: "KissKH",
    anime: false,
    async run(data, http) {
        if (!data.title) return empty();
        const headers = { "User-Agent": USER_AGENT, "Accept": "application/json", "Referer": BASE + "/" };
        const type = data.type === "movie" ? 2 : 1;
        const results = parseJson((await http.get(BASE + "/api/DramaList/Search?q=" + encodeURIComponent(data.title) + "&type=" + type, headers)).body);
        const show = pick(results, data);
        if (!show) return empty();

        const detail = parseJson((await http.get(BASE + "/api/DramaList/Drama/" + show.id + "?isq=false", headers)).body) || {};
        const episodes = detail.episodes || [];
        const episode = data.type === "movie" ? episodes[0] : episodes.find(e => Number(e.number) === Number(data.episode));
        if (!episode) return empty();

        // Keys for the video and subtitle endpoints, generated by enc-dec.app.
        const [videoKey, subKey] = await Promise.all([
            encGet(http, "enc-kisskh", { text: episode.id, type: "vid" }),
            encGet(http, "enc-kisskh", { text: episode.id, type: "sub" })
        ]);
        const [video, subs] = await Promise.all([
            videoKey ? http.get(BASE + "/api/DramaList/Episode/" + episode.id + ".png?err=false&ts=&time=&kkey=" + videoKey, headers).then(r => parseJson(r.body)) : null,
            subKey ? http.get(BASE + "/api/Sub/" + episode.id + "?kkey=" + subKey, headers).then(r => parseJson(r.body)) : null
        ]);

        const streams = [];
        // `ThirdParty` is an embed page, not a video.
        if (video && isHttp(video.Video)) {
            streams.push({ url: video.Video, source: "KissKH", quality: "", headers: { "Referer": BASE + "/", "Origin": BASE } });
        }
        // Subtitles are encrypted: enc-dec.app serves them decrypted.
        const subtitles = (Array.isArray(subs) ? subs : []).filter(s => s && isHttp(s.src))
            .map(s => ({ url: ENC_DEC + "/dec-kisskh?url=" + encodeURIComponent(s.src), label: languageName(s.label || s.land), lang: s.land || "" }));
        return { streams, subtitles };
    }
};
